'use strict';
// P2b: write the ES-module tree.
//
// `emit` runs the P1 unit conversion in memory first (it never reads a P1
// tree from disk), re-analyses the converted monolith, and writes
//   <out>/rts.html            the page, inline script replaced by one <script type="module">
//   <out>/rts/package.json    {"type":"module"}
//   <out>/rts/**.js           one module per section + 69 unit-art modules
// then proves the result: `node --check` on every file, and a real `import()`
// of main.js under the DOM stub rts.test.js uses.

